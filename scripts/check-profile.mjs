// Development only. Checks the app/profile.js customisation in Chromium; no TV contacted.
import { openPreview } from './browser.mjs';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] || '.local/qa/profile'; mkdirSync(out, { recursive: true });
const { browser, baseURL, close } = await openPreview({ publicFonts: true });
let fails = 0; const ok = (n, c, d) => { console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : ' ' + JSON.stringify(d))); if (!c) fails++; };
try {
  const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(String(e)));
  await p.addInitScript(() => { const D = Date; window.Date = class extends D { constructor(...a) { super(...(a.length ? a : [2026, 10, 1, 23, 9])); } static now() { return new D(2026, 10, 1, 23, 9).getTime(); } }; });
  await p.goto(baseURL + '/home/'); await p.waitForFunction(() => window.ShoreQA && window.ShoreQA.state());
  await p.waitForTimeout(800);
  let s = await p.evaluate(() => window.ShoreQA.state());
  const look = await p.evaluate(() => JSON.parse(localStorage.getItem('cleanframe.home.v1')).look);
  ok('First launch seeds Dock order', JSON.stringify(s.dock) === JSON.stringify(['netflix','youtube','5b8c3eb16b.BeamCTVDev','org.tizen.tv-viewer']), s.dock);
  ok('Dark background + Dock layout saved', look.bg === 'dark' && look.layout === 'dock', look);
  const clock = (await p.locator('#caption').innerText()).trim();
  ok('24-hour clock shows 23:09', /^23:09/.test(clock), clock);
  const css = await p.evaluate(() => { const t = document.querySelector('.track'); const u = document.querySelector('.quiet-utils .u, .u'); return { cls: document.documentElement.className, tr: getComputedStyle(t).transitionDuration, wc: getComputedStyle(t).willChange, ts: u ? getComputedStyle(u).textShadow : 'none' }; });
  ok('Low-motion: class, no track transition, no will-change, no text-shadow', /cf-low-motion/.test(css.cls) && css.tr === '0s' && css.wc === 'auto' && css.ts === 'none', css);
  await p.screenshot({ path: out + '/home-1920.png' });
  await p.locator('#stage').click();
  const where = () => p.evaluate(() => window.ShoreQA.where());
  await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight');
  s = await p.evaluate(() => window.ShoreQA.state());
  ok('Right x2 selects HBO Max', s.sel === '5b8c3eb16b.BeamCTVDev' || JSON.stringify(await where()).includes('BeamCTVDev'), [s.sel, await where()]);
  await p.screenshot({ path: out + '/home-hbo-focus-1920.png' });
  await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight');
  ok('Right does not wrap past Live TV', JSON.stringify(await where()).includes('tv-viewer') || (await p.evaluate(() => window.ShoreQA.state())).sel === 'org.tizen.tv-viewer', await where());
  await p.keyboard.press('Enter'); await p.waitForTimeout(600);
  const msgW = await where(); const msg = await p.locator('#sheetView').innerText().catch(() => '');
  ok('OK on Live TV shows real "needs the TV" message, no fake success', msgW.view === 'message' && /TV/.test(msg), [msgW, msg.slice(0, 200)]);
  await p.screenshot({ path: out + '/live-tv-ok-browser-1920.png' });
  await p.keyboard.press('Escape'); const w0 = await where();
  ok('Back from message returns focus to Live TV', w0.view === 'home' && w0.focus === 'Live TV', w0);
  await p.keyboard.press('ArrowUp'); const w1 = await where();
  await p.keyboard.press('Escape'); const w2 = await where();
  ok('Up enters controls, Back returns to apps', w1.zone === 'util' && w2.zone === 'apps', [w1, w2]);
  await p.reload(); await p.waitForFunction(() => window.ShoreQA && window.ShoreQA.state()); await p.waitForTimeout(500);
  s = await p.evaluate(() => window.ShoreQA.state());
  ok('Reload keeps saved Dock', s.dock.length === 4 && s.dock[3] === 'org.tizen.tv-viewer', s.dock);
  await p.evaluate(() => { const v = JSON.parse(localStorage.getItem('cleanframe.home.v1')); v.look.bg = 'light'; v.home = ['youtube','netflix']; v.dock = v.home.slice(); localStorage.setItem('cleanframe.home.v1', JSON.stringify(v)); });
  await p.reload(); await p.waitForFunction(() => window.ShoreQA && window.ShoreQA.state()); await p.waitForTimeout(500);
  s = await p.evaluate(() => window.ShoreQA.state()); const l2 = await p.evaluate(() => JSON.parse(localStorage.getItem('cleanframe.home.v1')).look);
  ok('Saved preferences win over profile', JSON.stringify(s.dock) === '["youtube","netflix"]' && l2.bg === 'light', [s.dock, l2]);
  ok('No page errors', errs.length === 0, errs);
  const p2 = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
  await p2.goto(baseURL + '/home/'); await p2.waitForFunction(() => window.ShoreQA && window.ShoreQA.state()); await p2.waitForTimeout(800);
  await p2.screenshot({ path: out + '/home-1280.png' });
  await p2.locator('#stage').click(); await p2.keyboard.press('ArrowUp'); await p2.keyboard.press('ArrowRight'); await p2.keyboard.press('ArrowRight'); await p2.keyboard.press('Enter'); await p2.waitForTimeout(600);
  await p2.screenshot({ path: out + '/settings-1280.png' });
} finally { await close(); }
console.log(fails ? fails + ' failure(s)' : 'All profile checks passed'); process.exit(fails ? 1 : 0);
